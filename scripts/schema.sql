-- Loan Ledger schema
-- Two source sheets: Loan Due Consolidated + Consolidated NPA Account

create table if not exists public.loan_due (
  id bigint generated by default as identity primary key,
  branch text,
  loan_type text,
  sr_no text,
  acc_no text,
  name text,
  loan_date date,
  loan_amt numeric,
  rate numeric,
  due_date date,
  provision numeric,
  due_no numeric,
  last_inst_date date,
  npa_date date,
  due_inst numeric,
  due_int numeric,
  due_other numeric,
  total_due numeric
);

create table if not exists public.npa_accounts (
  id bigint generated by default as identity primary key,
  secured text,
  npa_type_id int,
  npa_type text,
  gl_code text,
  gl_name text,
  acc_no text,
  acc_name text,
  loan_date date,
  loan_amount numeric,
  due_date date,
  balance numeric,
  provision numeric,
  due_month int,
  lst_inst_date date,
  npa_date date,
  due_inst numeric,
  due_int numeric,
  percentage numeric,
  npa_amount numeric,
  br_id text,
  br_name text,
  inst_amount numeric,
  period_type text,
  mobile_no text,
  valuation numeric,
  acc_no_str text
);

create table if not exists public.datasets (
  id bigint generated by default as identity primary key,
  source_file text not null,
  sheet_label text not null,
  table_name text not null,
  row_count int not null default 0,
  total_amount numeric,
  imported_at timestamptz not null default now(),
  notes text
);

create index if not exists loan_due_branch_idx on public.loan_due (branch);
create index if not exists loan_due_loan_type_idx on public.loan_due (loan_type);
create index if not exists loan_due_acc_no_idx on public.loan_due (acc_no);
create index if not exists loan_due_total_due_idx on public.loan_due (total_due);

create index if not exists npa_accounts_type_idx on public.npa_accounts (npa_type);
create index if not exists npa_accounts_branch_idx on public.npa_accounts (br_name);
create index if not exists npa_accounts_gl_idx on public.npa_accounts (gl_name);
create index if not exists npa_accounts_acc_no_idx on public.npa_accounts (acc_no);

alter table public.loan_due enable row level security;
alter table public.npa_accounts enable row level security;
alter table public.datasets enable row level security;

drop policy if exists "public read loan_due" on public.loan_due;
create policy "public read loan_due" on public.loan_due for select to anon, authenticated using (true);

drop policy if exists "public read npa_accounts" on public.npa_accounts;
create policy "public read npa_accounts" on public.npa_accounts for select to anon, authenticated using (true);

drop policy if exists "public read datasets" on public.datasets;
create policy "public read datasets" on public.datasets for select to anon, authenticated using (true);
